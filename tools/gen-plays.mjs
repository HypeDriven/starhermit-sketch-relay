// Writes the full-relay play scripts in tests/native/ from the rules' word
// table (src/rules.js WORDS_BY_PLAYER): every prompt typed in order, with a
// wrong guess now and then, through to the results.
//   relay-keys.play     desktop: typed into the focused field, Enter submits
//   relay-phone.play    a DPR-3 phone: the finger taps the field and Submit
//   relay-land.play     a DPR-3 phone sideways (short landscape layout), keys
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { WORDS_BY_PLAYER } from '../src/rules.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const words = WORDS_BY_PLAYER.flat();
const head = (title, viewport, start) => [
  `# Generated by tools/gen-plays.mjs: ${title}`,
  ...(viewport ? [`# viewport ${viewport}`] : []),
  'until 300 =Play',
  'frames 150',
  `${start} =Play`,
  'until 120 Time left',
  'frames 60',
];
const tail = [
  'until 120 All words completed!',
  'frames 30',
  'expect Words solved: 36 of 36',
  'expect Best round: 36/36',
];

function keys(viewport, name) {
  const out = head(`${name}: all 36 prompts typed and sent with Enter (a wrong guess every fifth).`, viewport, viewport ? 'touch' : 'click');
  if (viewport) out.push('touch Type a word and press Enter', 'frames 5');
  words.forEach((w, i) => {
    if (i % 5 === 2) out.push('type nope', 'frames 2', 'key Enter 1', 'frames 3', 'expect is not the prompt');
    out.push(`type ${w}`, 'frames 2', 'key Enter 1', 'frames 3');
    if (i === 4) out.push(`save ${name}-round`);
  });
  out.push(...tail, `save ${name}-results`, `expect Guesses: ${words.length + words.filter((_, i) => i % 5 === 2).length}`, 'click =Back to title', 'until 60 =Play', 'frames 10');
  return out.join('\n') + '\n';
}
function phone() {
  const name = 'relay-phone';
  const out = head(`${name}: a DPR-3 phone; the finger taps the field, types each prompt and taps Submit.`, '390x844@3', 'touch');
  words.forEach((w, i) => {
    out.push('touch Type a word and press Enter', 'frames 5', `type ${w}`, 'frames 2', 'touch =Submit', 'frames 5');
    if (i === 0) out.push('expect Correct! Next prompt.', `save ${name}-round`);
    if (i === 6) {
      out.push('touch =Pause', 'until 60 =Resume', 'frames 10', `save ${name}-pause`, 'touch =Resume', 'frames 10');
    }
  });
  out.push(...tail, `save ${name}-results`, 'touch =Back to title', 'until 60 =Play', 'frames 10', `save ${name}-title`);
  return out.join('\n') + '\n';
}
writeFileSync(join(root, 'tests/native/relay-keys.play'), keys(null, 'relay-keys'));
writeFileSync(join(root, 'tests/native/relay-land.play'), keys('844x390@3', 'relay-land'));
writeFileSync(join(root, 'tests/native/relay-phone.play'), phone());
console.log('wrote tests/native/relay-keys.play, relay-land.play, relay-phone.play');
